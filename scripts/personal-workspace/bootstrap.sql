CREATE ROLE authenticated NOLOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE ROLE authenticator LOGIN PASSWORD 'workspace-local-test-only' NOINHERIT;
GRANT authenticated, anon TO authenticator;
CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid $$;
GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;
CREATE TABLE public.vihem_profiles(id uuid PRIMARY KEY REFERENCES auth.users, name text, role text, active boolean, organisation_id uuid);
ALTER TABLE public.vihem_profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_profile ON public.vihem_profiles FOR SELECT TO authenticated USING(id=auth.uid());
GRANT SELECT ON public.vihem_profiles TO authenticated;
CREATE TABLE public.vihem_notifications(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,organisation_id uuid,title text,message text,type text,link text,read_at timestamptz,created_at timestamptz DEFAULT now());
CREATE SCHEMA storage;
CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
CREATE TABLE storage.objects(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),bucket_id text,name text);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE FUNCTION storage.foldername(text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$ SELECT string_to_array($1,'/') $$;
GRANT USAGE ON SCHEMA storage TO authenticated;
GRANT ALL ON storage.objects TO authenticated;
