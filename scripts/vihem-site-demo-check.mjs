import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
// Import the small client-only model without depending on Node's TS support.
const source=readFileSync(new URL('../apps/vihem-site/src/demoModel.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {initialDemo,createDemoOrder}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const a=initialDemo(),b=initialDemo();a.rooms[0].condition='Bra';
assert.equal(b.rooms[0].condition,null,'Reset must return independent unreviewed rooms');
assert.equal(b.rooms.filter(r=>r.condition).length,0);
const draft={title:'  Byt kran åäö  ',description:'Test',apartment:'1002',assignee:'Maja Demo'};
const assigned=createDemoOrder(b.orders,draft);
assert.equal(assigned.status,'Tilldelad');assert.equal(assigned.title,'Byt kran åäö');assert.equal(assigned.apartment,'1002');
const next=createDemoOrder([...b.orders,assigned],{...draft,assignee:''});
assert.ok(next.id>assigned.id);assert.equal(next.status,'Ny');
const tenant=createDemoOrder(b.orders,draft,true);
assert.equal(tenant.apartment,'1001');assert.equal(tenant.assignee,'');assert.equal(tenant.status,'Ny');assert.equal(tenant.tenantVisible,true);
assert.throws(()=>createDemoOrder(b.orders,{...draft,title:'  '}),/Ange en titel/);
assert.equal(createDemoOrder(b.orders,{...draft,title:'x'.repeat(150),description:'y'.repeat(1200)}).title.length,100);
assert.equal(createDemoOrder(b.orders,{...draft,description:'y'.repeat(1200)}).description.length,1000);
assert.equal(b.orders.length,2,'Creation must not mutate initial example data');
console.log('PASS VI-HEM click demo: independent reset, unreviewed rooms, assignment, IDs, tenant context, validation and size limits.');
